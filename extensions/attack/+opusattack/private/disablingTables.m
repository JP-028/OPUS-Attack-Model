function [flow,event,participants] = disablingTables(report)
    k=report.shell; time=report.time_year; count=report.disabled_count;
    flow=cell2table({'disabling',k,k,char(report.owner_id),'',char(report.population),'','D',char(report.owner_id), ...
        time,time,count,count,count},'VariableNames', ...
        {'process','shell','destination_shell','owner_id','counterpart_owner_id', ...
        'population','counterpart_population','destination_population','destination_owner_id', ...
        'start_time','end_time','quantity','source_count','destination_count'});
    event=flow;
    event.event_id=report.log_event_id;
    event.record_kind="instantaneous_attack";
    event.event_time=time;
    participants=table(report.log_event_id,report.owner_id,"affected",report.population, ...
        'VariableNames',{'event_id','owner_id','role','population'});
end
